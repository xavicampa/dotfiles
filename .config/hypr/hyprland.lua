-- ─── HDR output (homepc only) ─────────────────────────────────────────────
-- The MPG321UX is HDR10-capable (hyprctl hardwareDetails: hdr/bt2020 yes) but the
-- default cm preset is srgb, so clients never see PQ/BT2020 — Chrome's HDR-video
-- path (WaylandHdrSurface) reads output color caps via color-management-v1, and on
-- srgb YouTube only ever serves vp9 profile0 (SDR). cm=hdr programs the output with
-- the PQ transfer function (10-bit already: DMS's rule sets bitdepth=10, confirmed
-- by currentFormat XRGB2101010). Kept AFTER require("dms.outputs") so the field
-- override wins and it survives DMS regenerating outputs.lua; do NOT merge it into
-- outputs.lua (regenerated, manual edits there are lost).
-- GOTCHA 2026-11-20: the panel's DDC/CI MCU wedged after the output reprogramming
-- during HDR enable (ddcutil: comms dead on i2c-11, i2c-16 reads but writes fail
-- DDCRC_VERIFY). NOT the preset itself — identical failure under cm=srgb — a power
-- cycle of the display fully restored DDC/CI (VCP 2.1, writes verified). If
-- brightness keys ever go dead again: power-cycle the monitor before suspecting
-- Hyprland/Chrome.
-- SDR-in-HDR tone mapping + the brightness ladder (2026-11-21, mode-aware):
-- only F11/F12 (+XF86MonBrightness*) — SHIFT+F11/F12 is unbound again. The
-- ladder follows the output's color-management mode; the SWITCH is DMS
-- Settings -> Displays ("Color gamut" picker; see dms_cm_value below —
-- "auto" keeps the HDR default). Both modes end at DMS software brightness:
--   HDR (cm=hdr/hdredid): SDR white 400->80 (top) -> DMS software (soft-down/soft-up).
--   SDR (cm=wide/dcip3/dp3/adobe/edid): panel DDC (top, bright-hybrid.sh
--                    up/down, software crossover at the DDC floor) -> DMS software.
-- sdr_min_luminance 0.005 sits desktop black on the OLED's true black (default
-- 0.2 lifts it); sdr_max_luminance (bind range 80-400 nits) is the
-- perceived desktop/SDR brightness. The closure seeds from SDR_MAX because
-- the HL.Monitor object
-- exposes no getter for these fields. hl.monitor() at runtime applies
-- instantly (no reload/flicker); each press re-registers the rule (last one
-- wins) and the value survives config reloads/restarts via the state file.
-- 2026-11-21: the running Hyprland carries the local #16329 reference_luminance patch
-- v2 — "advertise" variant (NOTES.md § hyprland): reference_luminance replaces the
-- hard-coded HDR_REF_LUMINANCE ONLY in what clients are told (output + surface
-- preferred descriptions + wp_color_management_output), never in the render-side
-- description, so HDR video tonemapping (which scales by dstRef/srcRef — the v1
-- incident that crushed video shadows at low values) is untouched.
-- The slider drives sdr_max_luminance (untagged/XWayland SDR) AND reference_luminance
-- (Chrome/Slack SDR anchoring, re-advertised live) together, so one knob moves the
-- whole desktop. Range 80-400 (400 ≈ this panel's TrueBlack-400 sustained white);
-- seed 200 keeps the old HDR_REF_LUMINANCE-anchored look.
local SDR_MAX = 200            -- fallback seed only; the state file below wins
local SDR_MAX_CAP = 400
if HOST == "homepc" then
    -- HDR detection: DMS Settings -> Displays has a per-output "Color gamut"
    -- picker (values auto/wide/dcip3/dp3/adobe/edid/hdr/hdredid — no "srgb" in
    -- this UI); it stores hyprlandOutputSettings.<out>.colorManagement in
    -- ~/.local/state/dms/session.json AND (when non-auto) writes cm= into the
    -- required dms/outputs.lua — whose rewrite Hyprland's config watcher picks up,
    -- re-running this block. So the DMS UI IS the HDR switch; read session.json
    -- here so rule + ladder follow it. nil/"auto" keeps the historical default
    -- (this config used to hardcode cm=hdr, session.json sat at auto). All these
    -- values are valid Hyprland cm= values (v0.57.2 CMType.cpp), so MON_CM can
    -- go straight into the rule.
    local function dms_cm_value()
        local f = io.open((os.getenv("HOME") or "") .. "/.local/state/dms/session.json", "r")
        if not f then return nil end
        local s = f:read("*a")
        f:close()
        return s and s:match('"HDMI%-A%-1".-colorManagement"%s*:%s*"([^"]+)"')
    end
    local CM_VALUE = dms_cm_value()
    local MON_CM = (CM_VALUE and CM_VALUE ~= "auto") and CM_VALUE or "hdr"
    local MON_HDR = MON_CM:find("^hdr") ~= nil   -- hdr / hdredid only; the rest are SDR gamuts
    local function mon_rule(v)
        return { output = "HDMI-A-1", bitdepth = 10,
                 cm = MON_CM,
                 sdr_max_luminance = v, reference_luminance = v,
                 sdr_min_luminance = 0.005 }
    end
    -- sdr_max is PERSISTED: the soft-lane crossover restarts the DMS shell, which
    -- rewrites the required dms/*.lua fragments (colors.lua, layout.lua), which
    -- Hyprland's config watcher auto-reloads mid-ladder — a bare closure got
    -- re-seeded to 200 right at the crossover ("climbing from software lands at
    -- 200"). With the state file, ANY reload/restart resumes where you left off.
    local SDR_STATE = (os.getenv("HOME") or "") .. "/.local/state/hypr/sdr-max"
    local function sdr_state_read()
        local f = io.open(SDR_STATE, "r")
        if not f then return nil end
        local v = tonumber(f:read("*a") or "")
        f:close()
        return v
    end
    local sdr_max = math.max(80, math.min(SDR_MAX_CAP, sdr_state_read() or SDR_MAX))
    hl.monitor(mon_rule(sdr_max))
    local function set_sdr_max(v)
        sdr_max = math.max(80, math.min(SDR_MAX_CAP, v))
        hl.monitor(mon_rule(sdr_max))
        local sf = io.open(SDR_STATE, "w")
        if sf then sf:write(tostring(sdr_max)); sf:close() end
        -- DMS-styled slider OSD via the sdrLevelOsd daemon plugin
        -- (~/.config/dms/plugins/sdrLevelOsd) — reuses DMS's own LevelOSD/DOSD
        -- chrome so it looks exactly like the brightness/volume OSD and follows
        -- the OSD position setting. Value/min/max travel as IPC args.
        hl.exec_cmd("dms ipc call sdrLevelOsd show " .. sdr_max ..
                    " 80 " .. SDR_MAX_CAP .. " 'SDR white'")
    end
    -- TRAP 2026-11-21: inside Lua callbacks use hl.exec_cmd (runs immediately).
    -- hl.dsp.exec_cmd is a DEFERRED bind-action constructor (bind(key, ...) form;
    -- Emergency.hpp shows the calling form hl.dispatch(hl.dsp.exec_cmd(x)));
    -- calling it bare in a callback is a silent no-op — that was the dead-keybind bug.
    local BRIGHT_SCRIPT = "/home/javi/.config/hypr/scripts/bright-hybrid.sh"
    -- "software mode" marker = the systemd user override bright-hybrid.sh writes
    -- when it restarts dms.service with DMS_NO_DDC=1. io.open is the only way the
    -- Lua config can see the mode (no io.popen/os.execute).
    local SOFT_OVERRIDE = (os.getenv("HOME") or "") .. "/.config/systemd/user/dms.service.d/override.conf"
    local function soft_mode_on()
        local f = io.open(SOFT_OVERRIDE, "r")
        if f then f:close(); return true end
        return false
    end
    local function bright_down()
        if not MON_HDR then
            hl.exec_cmd(BRIGHT_SCRIPT .. " down")          -- SDR ladder: DDC, crosses to software at its floor
        elseif sdr_max > 80 then
            set_sdr_max(sdr_max - 20)                      -- HDR ladder: SDR white segment
        else
            hl.exec_cmd(BRIGHT_SCRIPT .. " soft-down")     -- bottom lane: DMS software (DDC skipped in HDR)
        end
    end
    local function bright_up()
        if soft_mode_on() then
            hl.exec_cmd(BRIGHT_SCRIPT .. " soft-up")       -- climb; leaves the lane at 100 (DMS restart)
        elseif MON_HDR then
            set_sdr_max(sdr_max + 20)                      -- HDR ladder: SDR white segment
        else
            hl.exec_cmd(BRIGHT_SCRIPT .. " up")            -- SDR ladder: DDC
        end
    end
    hl.unbind("F11")
    hl.unbind("F12")
    hl.bind("F11", bright_down, { locked = true, repeating = true,
              description = "brightness down: (HDR) SDR white 400->80 / (SDR) panel DDC, then DMS software" })
    hl.bind("F12", bright_up, { locked = true, repeating = true,
              description = "brightness up: DMS software, then (HDR) SDR white (cap 400) / (SDR) panel DDC" })
    hl.bind("XF86MonBrightnessDown", bright_down, { locked = true, repeating = true,
              description = "brightness down ladder (laptop keys; unreachable on the Ducky)" })
    hl.bind("XF86MonBrightnessUp", bright_up, { locked = true, repeating = true,
              description = "brightness up ladder (laptop keys; unreachable on the Ducky)" })

    -- Chromium/Electron HDR retag fix (2026-11-23): on a PQ output, Chromium
    -- re-tags its UI surface as BT2020/PQ with luminances (0, 1000, ref=knob)
    -- (WAYLAND_DEBUG dump: set_primaries_named(6) set_tf_named(11)
    -- set_luminances(0,1000,knob) ~36ms after the plain sRGB tag). Hyprland's
    -- getCMSettings then treats the UI as HDR content: needsSDRmod=false (so
    -- sdr_max_luminance never applies) and the declared 1000-nit volume gets
    -- tone-mapped into the panel's 455 — at knob 150 that lands white at ~101
    -- nits, ~1/3 darker than untagged apps sitting exactly at the knob.
    -- tonemap="clamp" (the parser takes names, not digits: on/off/clamp/limited,
    -- WindowRule.cpp) is the shader's clamp-passthrough (tonemap.glsl guard):
    -- PQ passes 1:1, so Electron white lands at the knob like everything else.
    -- google-chrome included: it tags EVERY surface PQ (0,1000,ref=knob) from
    -- startup, and inline YouTube video is composited into the same surface, so
    -- no per-surface split is possible. On this 455-nit panel clamp is also the
    -- more faithful video path: content <=455 nits renders at true nits instead
    -- of being compressed (a 300-nit highlight: ~163 nits tonemapped vs 300
    -- clamped); only >455-nit speculars hard-clip instead of rolling off.
    -- No-op in SDR modes (no tonemap triggers there).
    hl.window_rule({ match = { class = "^(slack|empower-electron|google-chrome)$" }, tonemap = "clamp" })
end

-- ─── Dictate: push-to-talk dictation (homepc only) ────────────────────────
-- The NixOS config (~/.config/nixos/homepc/configuration.nix, systemd.user.services.dictate)
-- runs an always-on daemon (Whisper on the Intel NPU via OpenVINO GenAI); these
-- binds drive it over $XDG_RUNTIME_DIR/dictate.sock.
-- Hold SUPER+CTRL+H to capture, RELEASE to stop + transcribe the segment
-- (segments are also auto-cut mid-hold on ~0.6s of silence). Output:
-- ~/dictation/YYYY-MM-DD.md + clipboard + a DMS notification.
-- Hyprland 0.56's Lua API has no hl.bindz — the bindz equivalent is
-- hl.bind(..., { release = true }); the handler may be a Lua function
-- (exec_cmd spawns through Hyprland's executor). Absolute path because the
-- hyprland/uwsm unit env's PATH is not guaranteed to carry the system profile.
-- SUPER+CTRL+H was DMS's focus-monitor-left chord (dms/binds.lua:76) — the
-- unbind here (which loads AFTER require("dms.binds")) frees it; the same
-- action stays reachable on SUPER+CTRL+left.
if HOST == "homepc" then
    local dictate_bin = "/run/current-system/sw/bin/dictate"
    hl.unbind("SUPER + CTRL + H")
    hl.bind("SUPER + CTRL + H", function() hl.exec_cmd(dictate_bin .. " start-capture") end,
            { description = "dictate: start capture (hold)" })
    hl.bind("SUPER + CTRL + H", function() hl.exec_cmd(dictate_bin .. " stop-capture") end,
            { release = true, description = "dictate: stop + transcribe (release)" })
end
