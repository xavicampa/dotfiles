-- Hyprland Lua config root (Hyprland 0.55+) — DMS defaults only.
--
-- Your legacy settings are disabled: the full port of the old hyprlang config
-- (env vars, ALT mainMod binds, animations, input, windowrules, ddcutil media
-- keys) is parked in ~/.config/hypr/legacy/hyprland.lua.bak — `cp` it over this file to
-- restore. The pre-Lua hyprlang original sits beside it as legacy/hyprland.conf (both are
-- versioned in the dotfiles repo). Keybind inventory: ~/.config/hypr/keybinds.md
--
-- Hyprland loads hyprland.lua *instead of* hyprland.conf when this file exists,
-- and DMS keeps hyprland.conf as a stub, so this file is the only entry point.
-- Reference: https://wiki.hypr.land/configuring/

-- ─── Host identity (FIRST: every host-gated block below reads HOST) ────────
-- This file is shared by every host in the dotfiles repo (homepc, dell), but the
-- two machines run different stacks: homepc = Hyprland + DMS (DankMaterialShell,
-- programs.dms-shell declared in ~/.config/nixos/homepc/configuration.nix), dell =
-- bare Hyprland (waybar + dunst + hypridle + hyprlock, see
-- ~/.config/nixos/dell/configuration.nix). So the dms/* requires must not run on
-- the dell: those fragments are DMS-generated AND gitignored, i.e. they exist only
-- on the machine that runs DMS — on the dell require("dms.colors") would fail
-- outright and take the whole config down.
-- /etc/hostname is the primary source — NixOS writes it from networking.hostName —
-- because HOSTNAME is a shell variable and is not guaranteed in a uwsm/systemd-user
-- spawned Hyprland. os.getenv is available in the Lua config; os.execute is not
-- (upstream bug), so do not shell out for this.
-- HYPR_HOST is a validation hook only, for checking a host branch you are not on:
--   HYPR_HOST=dell Hyprland --verify-config
-- Do not set it in a real session.
local function hostname()
    local h = os.getenv("HYPR_HOST")
    if h and h ~= "" then return h:gsub("%s+$", "") end
    local f = io.open("/etc/hostname", "r")
    h = f and f:read("l") or nil
    if f then f:close() end
    h = (h and h ~= "") and h or os.getenv("HOSTNAME")
    return (h or ""):gsub("%s+$", "")
end
local HOST = hostname()

