-- ─── No wallpapers / no Hyprland chrome ────────────────────────────────────
-- Hyprland is not a wallpaper daemon, but it still paints a background layer of
-- its own: with force_default_wallpaper = -1 (the default) it picks a random
-- image out of $XDG_DATA_HOME/../share/hypr/wall{0,1,2}.png — nixpkgs ships the
-- anime mascots there (/run/current-system/sw/share/hypr), so they DO render on
-- this box — and disable_hyprland_logo = false adds the random Hyprland logo /
-- anime-girl background on top of that. Both off => plain background_color
-- (misc.background_color, default 0xff111111). No wallpaper daemon runs here
-- (hyprpaper/swww/swaybg are all absent from the session), so this is the only
-- thing between the panels and flat dark grey. Kept hand-owned: DMS never
-- writes misc.*.
-- Live equivalent while a session is up — `hyprctl keyword` is REJECTED for a
-- Lua config ("keyword can't work with non-legacy parsers. Use eval."):
--   hyprctl eval 'hl.config({ misc = { force_default_wallpaper = 0, disable_hyprland_logo = true, disable_splash_rendering = true } })'
-- ~/.config/hypr/hyprpaper.conf (preload/wallpaper = ~/.config/i3/tokyonight.jpg)
-- was moved to ~/.config/hypr/legacy/hyprpaper.conf.disabled — nothing started
-- hyprpaper anyway, and DMS's Wallpaper page (SUPER + comma) / dash wallpaper tab
-- (SUPER + Y) no longer have a config to pick up. The jpg itself is untouched.
hl.config({
    misc = {
        force_default_wallpaper  = 0,
        disable_hyprland_logo    = true,
        disable_splash_rendering = true, -- no "Hyprland" splash text on boot
    },
})

-- ─── Host identity: monitor blocks ────────────────────────────────────────
-- HOST is set at the top of this file (nothing can be host-gated before it).
-- DMS regenerates ~/.config/hypr/dms/outputs.lua for whatever panels are attached
-- to the machine it runs on, and that ONE tracked file would otherwise leak homepc's
-- HDMI-A-1/DP-3 layout onto the dell (and vice versa) — hence the guard, even though
-- outputs.lua is only regenerated on homepc today.

-- DMS's auto-generated monitor block (mode/position/scale/VRR). Tracked in the
-- repo because it is the ONLY durable home of the display scale — settings.json
-- never carries it. Guarded per host; add a `elseif HOST == "dell"` branch with a
-- hand-written hl.monitor() if that laptop starts running DMS (its old monitor +
-- touchpad stanzas are parked in legacy/dell.conf, currently inert).
if HOST == "homepc" then
    require("dms.outputs")
end

-- ─── Kill the ghost DP-3 output ────────────────────────────────────────────
-- Only HDMI-A-1 (Microstep MPG321UX) is physically attached, but the DP-3 port
-- still reports an EDID (same model AND same bogus serial 0x01010101 as HDMI-A-1,
-- and ddcutil sees ddc:i2c-16), so DMS regenerates outputs.lua with DP-3 enabled
-- at 2880x0. Hyprland then spreads workspaces across two "monitors": ws 1/2/3 live
-- on the invisible DP-3, so `SUPER + 1/2/3` switch *there* (nothing visible) while
-- `SUPER + 4+` create fresh workspaces on HDMI-A-1 (looks like it "works from 4").
-- The legacy hyprland.conf had `monitor=DP-3, disable` (see
-- legacy/homepc.conf:9, inert since the Lua migration); that was lost in the
-- migration. Kept AFTER require("dms.outputs") so it wins
-- over the auto-generated stanza and survives DMS rewriting that file.
-- Remove this when a second panel actually goes on the DP port.
if HOST == "homepc" then
    hl.monitor({ output = "DP-3", disabled = true })
end
