-- NOTE: dms/binds-user.lua is REGENERATED by `dms keybinds set/remove` — it
-- rewrites the whole file, normalizes [[...]] strings to escaped quotes, adds an
-- hl.unbind() before every bind, and DROPS all comments. Keep prose here.
--
-- Brightness (DDC/CI) binds now living in dms/binds-user.lua:
--   No /sys/class/backlight on this box — both MSI MPG321UX panels are DDC-only
--   (ddc:i2c-11 = HDMI-A-1, ddc:i2c-16 = DP-3). DMS's default binds pass "" as the
--   device, which lands on the wrong default device and, with DMS 1.6.2, on a stale
--   DDC cache (upstream #3616: initial read fails -> max=0 cached, ForceRescan skips
--   it), so an "increment" could *lower* the panels. Naming the device sidesteps it.
--   Both panels share an EDID serial (0x01010101), so DDC writes move them together
--   either way — one device id is enough; the old per-monitor F1-F4 split is moot.
--   Re-check ids after a replug/reboot: `dms brightness list --ddc`
--   The XF86MonBrightness* keysyms are UNREACHABLE on the Ducky One 3 Mini (its
--   kernel keybit advertises VOLUME*/MEDIA keys but no KEY_BRIGHTNESSDOWN(224)/UP(225)
--   — a desktop board has no display to map an Fn combo to); kept only for a laptop.
--   Real keys on this board: F11/F12 = Fn + - / Fn + = (60% board, F1-F12 unbound).
--
-- Scratch workspace (special:magic), bound via `dms keybinds set`:
--   SUPER+S = toggle, SUPER+SHIFT+S = move window there. Chosen because Hyprland's
--   legacy `code:61` is XKB keycode 61 = <AB10> = minus/underscore on the `no`
--   layout, which collides with DMS's SUPER+minus resize bind. Letters are
--   layout-stable; keysym names like `grave` are not (no(basic) has no `grave`).

-- ─── Input: DMS-overridable baseline ───────────────────────────────────────
-- Only knobs that DMS's Settings -> Input can also write live here, so when
-- 1.7 starts generating dms/input.lua there is exactly one owner per key: the
-- Settings UI. DMS writes only rows you actually touched, so untouched keys
-- keep these values.
--   Ported from legacy/hyprland.lua.bak. It said -1.9, but Hyprland clamps
--   sensitivity to [-1.0, 1.0], so -1.9 was already landing on -1.0.
--   Raise toward 0 if it feels too slow.
hl.config({
    input = {
        sensitivity  = -1.0,
        follow_mouse = 1,
    },
})

-- ─── Input precedence ─────────────────────────────────────────────────────
-- dms/input.lua is DMS-generated output, never hand-edit it: `dms setup` only
-- fills fragments that are missing OR EMPTY, so a stray comment in that file
-- permanently disables the Input page. It is an empty stub on dms 1.6.3 (no
-- Input page; `dms setup` has no `input` subcommand) and a no-op today.
-- Requiring it HERE means: baseline above -> DMS overrides -> hand-owned below.
if HOST == "homepc" then
    require("dms.input")
end

-- ─── Input: hand-owned (loads after dms.input, so it always wins) ─────────
-- DMS's Input page has a Keyboard section, so kb_* must sit below the require
-- or a Settings change could silently take them over. These are load-bearing:
--   kb_layout — Hyprland ignores /etc/X11/xorg.conf.d and systemd-localed, so
--   it stays "us" unless set here. NixOS sets the system layout via
--   services.xserver.xkb.layout = "no" (drives the greeter + DMS's readout).
--   kb_options — physical Alt sends Super (DMS's SUPER binds land on it) and
--   physical Win sends Alt (app Alt+Tab / Alt+PgDn move there). NixOS sets the
--   same option for the greeter + console; Hyprland needs its own copy. Left
--   out terminate:ctrl_alt_bksp (X11-only).
hl.config({
    input = {
        kb_layout  = "no",
        kb_options = "altwin:swap_lalt_lwin",
    },
})

-- Natural scroll on the G Pro — per-device, which DMS's Input page cannot
-- express (it writes global input:natural_scroll, which would invert every
-- pointer, including the Ducky's phantom mouse interface). The .bak also had
-- "logitech-g-pro-wireless-gaming-mouse-2", which no longer enumerates.
-- Current pointers: logitech-g-pro--1, ducky-ducky-one-3-mini-rgb-2 (keyboard HID).
hl.device({ name = "logitech-g-pro--1", natural_scroll = true })

-- ─── Host: the dell's own fragment ────────────────────────────────────────
-- The dell runs no DMS, so everything dms/* would have set there (monitor, cursor
